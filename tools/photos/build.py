"""Write assets/js/photos.js from credits.json (Commons metadata) and captions.json."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
credits = json.load(open(os.path.join(ROOT, "assets/img/photos/credits.json")))
caps = json.load(open(os.path.join(ROOT, "tools/photos/captions.json")))
ARTIST = {
  "mae-sai-towns": "Supanut Arunoprayote",
  "mombasa-port": "Kenya Ministry of East African Affairs, Commerce and Tourism",
  "gerd-space": "NASA/METI/AIST/Japan Space Systems and U.S./Japan ASTER Science Team",
  "mae-la": "Mikhail Esteves",
  "malaria-rwanda": "Amani Athar, USAID / President's Malaria Initiative",
  "xayaburi": "Prince Roy",
  "bukavu": "Abel Kavanagh, MONUSCO",
}
out = {}
for k, m in credits.items():
    if k not in caps: continue
    w, h = m["saved"]
    out[k] = {
        "src": f"assets/img/photos/{k}.jpg", "sm": f"assets/img/photos/{k}-sm.jpg", "w": w, "h": h,
        "file": m["title"].replace("File:", ""), "page": m["page"],
        "artist": ARTIST.get(k, m["artist"]), "license": m["license"], "licenseUrl": m["licenseUrl"],
        "cap": dict(zip(["en", "fr", "th", "sw"], caps[k])),
    }
js = ("/* Photographs used on the site, with credits. Generated by tools/photos/build.py\n"
      "   from Wikimedia Commons metadata; edit captions in tools/photos/captions.json. */\n"
      "window.CPM_PHOTOS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
open(os.path.join(ROOT, "assets/js/photos.js"), "w").write(js)
print(len(out), "photos")
